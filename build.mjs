// Builds telem-plus.js (the file the bookmarklet loads) from the extension sources,
// so the extension and the bookmarklet always share the same code.
//   node build.mjs
import { readFileSync, writeFileSync } from "node:fs";

const css = readFileSync(new URL("./extension/theme.css", import.meta.url), "utf8")
  .replace(/\/\*[\s\S]*?\*\//g, "")
  .replace(/\s+/g, " ")
  .trim();
const content = readFileSync(new URL("./extension/content.js", import.meta.url), "utf8");
const { version } = JSON.parse(readFileSync(new URL("./extension/manifest.json", import.meta.url), "utf8"));

const out = `/* תלם+ ${version} — generated by build.mjs from extension/. Do not edit by hand. */
(() => {
  if (location.hostname !== "telem.tel-aviv.gov.il") return;
  // The Chrome extension is already running in this tab: nothing to do.
  if (!window.__telemPlus && document.getElementById("tg-tools")) return;
  // Clicking the bookmarklet means "I want it on".
  try { localStorage.setItem("tg:enabled", "true"); } catch {}
  if (!document.getElementById("tg-style")) {
    const s = document.createElement("style");
    s.id = "tg-style";
    s.textContent = ${JSON.stringify(css)};
    (document.head || document.documentElement).appendChild(s);
  }
${content}
})();
`;
writeFileSync(new URL("./telem-plus.js", import.meta.url), out);
console.log(`telem-plus.js ${version}: ${(out.length / 1024).toFixed(1)} KB`);

// Firefox (desktop + Android) manifest. Orion on iPhone installs the same add-on from addons.mozilla.org.
const manifest = JSON.parse(readFileSync(new URL("./extension/manifest.json", import.meta.url), "utf8"));
manifest.host_permissions = ["https://telem.tel-aviv.gov.il/*"];
manifest.browser_specific_settings = {
  gecko: {
    id: "telem-plus@iftachts.github.io",
    strict_min_version: "140.0",
    data_collection_permissions: { required: ["none"] },
  },
  gecko_android: { strict_min_version: "142.0" },
};
writeFileSync(new URL("./firefox-manifest.json", import.meta.url), JSON.stringify(manifest, null, 2) + "\n");
console.log("firefox-manifest.json written (package with: ./package.sh)");
